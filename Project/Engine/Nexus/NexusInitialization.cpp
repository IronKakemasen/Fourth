template<>
void Nexus::Init<Nexus::InitSequence::kCoInitializeEx>()
{
	//COMの初期化
	HRESULT hr = CoInitializeEx(0, COINITBASE_MULTITHREADED);
	ErrorMessageOutput::Abort::DetectError(SUCCEEDED(hr), "CoInitializeEx()でエラー", fileName);
}
