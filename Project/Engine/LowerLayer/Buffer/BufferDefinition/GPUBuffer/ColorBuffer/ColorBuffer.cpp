ColorBuffer::ColorBuffer
(
	const InstanceKey& instanceKey_,
	std::string const& name_,
	std::vector<Microsoft::WRL::ComPtr<ID3D12Resource>> resourceContainer_,
	const BufferDescriptionBehavior& description_
) : GPUBufferBehavior(instanceKey_, name_, std::move(resourceContainer_), description_)
{
	//ステータスを同期
	SynchronizeStatus(numBuffer);
}
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
std::optional<D3D12_RESOURCE_BARRIER> ColorBuffer::CreateBarrier(BufferUsage usage_)
{
	int dstBufferIndex = ProperBufferIndex(usage_);

	//次のステート
	D3D12_RESOURCE_STATES nextState = ResourceStateTable(usage_);
	auto& dstBuffer = buffers.at(dstBufferIndex);
	
	//もし遷移予定のステートが現在ステートと一致していた場合はバリアを作らない
	if (IsStateSame(dstBufferIndex, nextState)) return std::nullopt;

	return dstBuffer.CreateBarrier(nextState);
}
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
