
#include "Presenter.h"


SwapChainContext::Presenter::Presenter(IDXGISwapChain4* swapChain_)
	:swapChain(swapChain_)
{

}
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
UINT SwapChainContext::Presenter::GetFrameIndex()const
{
	return swapChain->GetCurrentBackBufferIndex();
}
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
void SwapChainContext::Presenter::Present()const
{
	HRESULT hr = swapChain->Present(1, 0);
	ErrorMessageOutput::Assert::DetectError(SUCCEEDED(hr), "swapChain->Presentでエラー", "Presenter.cpp");
}
