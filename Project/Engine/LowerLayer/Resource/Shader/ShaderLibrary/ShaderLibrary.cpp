///+//////////////////////////////////////////////////////////////////////////////////////////////////////
///+//////////////////////////////////////////////////////////////////////////////////////////////////////
///+//////////////////////////////////////////////////////////////////////////////////////////////////////
IDxcBlob* ShaderContext::ShaderLibrary::Export(std::string fileName_)
{   
    ErrorMessageOutput::Assert::DetectError
    (
        data.find(fileName_) != data.end(),
        fileName_ + "このキーがそもそも存在しない", 
        fileName
    );

    ErrorMessageOutput::Assert::DetectError
    (
        data.at(fileName_),
        fileName_ + "このキーの中身がない",
        fileName
    );

    return data.at(fileName_).Get();
}
///+//////////////////////////////////////////////////////////////////////////////////////////////////////
///+//////////////////////////////////////////////////////////////////////////////////////////////////////
///+//////////////////////////////////////////////////////////////////////////////////////////////////////
void ShaderContext::ShaderLibrary::Import
(
    NexusFieldProof proof_, 
    const std::string& fileName_, 
    Microsoft::WRL::ComPtr<IDxcBlob>&& data_
)
{
    data[fileName_] = std::move(data_);
    Logger::Log("Import: " + fileName_, fileName);
}
