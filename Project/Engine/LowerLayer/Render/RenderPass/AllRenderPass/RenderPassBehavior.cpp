RenderContext::PassBehavior::PassBehavior(NexusFieldProof proof_, std::unique_ptr<PassDesc>&& desc_)
	:desc(std::move(desc_))
{
	
}

///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///+///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
RenderContext::PassDesc const* RenderContext::PassBehavior::WatchDesc() const
{
	return desc ? desc.get() : nullptr;
}
